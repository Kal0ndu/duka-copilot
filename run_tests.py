"""
run_tests.py - Step 10: run every offline test and save the evidence
======================================================================

Runs, without any API key:
  1. the pytest unit tests (tests/)
  2. the attack suite and its scorecard (attacks.py)
  3. the task scenarios and success rates (evaluation.py)
  4. the measured results: categorisation accuracy, forecast backtest, headline
and writes everything to docs/test_results.md for the submission.

The live Gemini test (tests/test_live_gemini.py) is skipped unless you turn it on.

HOW TO RUN
    py run_tests.py
"""

import platform
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from collections import Counter
from datetime import datetime
from pathlib import Path

from analytics import BUSINESSES, DATA, load_ledger
from attacks import run_attacks
from build_ledger import check_accuracy
from categoriser import categorise_all
from credit import headline
from evaluation import rate, run_evaluation
from forecast import backtest
from parser import parse_statement

ROOT = Path(__file__).parent
OUT = ROOT / "docs" / "test_results.md"


def run_pytest():
    """Run pytest; return per-file counts and any failures."""
    with tempfile.TemporaryDirectory() as tmp:
        report = Path(tmp) / "pytest.xml"
        subprocess.run([sys.executable, "-m", "pytest", "tests", "-q", "-p", "no:cacheprovider",
                        f"--junitxml={report}"], cwd=ROOT, capture_output=True, text=True)
        cases = ET.parse(report).getroot().iter("testcase")
        files, failures = {}, []
        for case in cases:
            name = case.get("classname").split(".")[-1]
            outcome = ("skipped" if case.find("skipped") is not None else
                       "failed" if case.find("failure") is not None
                       or case.find("error") is not None else "passed")
            files.setdefault(name, Counter())[outcome] += 1
            if outcome == "failed":
                failures.append(f"{name}::{case.get('name')}")
    return files, failures


def measured_results():
    accuracy, backtests = [], []
    for business in BUSINESSES:
        txns, report = parse_statement(DATA / f"{business}_statement.csv")
        categorise_all(txns, business)
        acc, _ = check_accuracy(txns, DATA / f"{business}_labels.csv")
        accuracy.append((business, len(txns), report["balance_mismatches"], acc))
        backtests.append((business, backtest(load_ledger(DATA / f"{business}_ledger.csv"))))
    return accuracy, backtests, headline()


def kes(x):
    return f"KES {x:,.0f}"


def write_report(files, failures, attacks, evaluation, accuracy, backtests, h):
    passed = sum(c["passed"] for c in files.values())
    failed = sum(c["failed"] for c in files.values())
    skipped = sum(c["skipped"] for c in files.values())
    blocked = sum(r[2] for r in attacks)
    s_pass, s_total = rate(evaluation["scripted"])
    p_pass, p_total = rate(evaluation["planner"])
    scripted = evaluation["scripted"]
    genuine = [x for x in scripted if x[0]["answer"] == "verified"]
    invented = [x for x in scripted if x[0]["answer"] == "fallback"]

    lines = [
        "# Duka Copilot - test results",
        "",
        f"Generated by `py run_tests.py` on {datetime.now():%Y-%m-%d %H:%M} "
        f"(Python {platform.python_version()}, {platform.system()}). "
        "Everything below ran **offline, without an API key**, on synthetic data only.",
        "",
        "## Summary",
        "",
        "| Check | Result |",
        "|---|---|",
        f"| Unit tests (pytest) | **{passed} passed**, {failed} failed, {skipped} skipped (live Gemini, off by default) |",
        f"| Attack suite | **{blocked} of {len(attacks)} attacks blocked** |",
        f"| Task scenarios, scripted mock AI (full pipeline) | **{s_pass}/{s_total} = {s_pass / s_total:.0%}** |",
        f"| Task scenarios, offline keyword planner (picks tools itself) | {p_pass}/{p_total} = {p_pass / p_total:.0%} |",
        f"| Number verification | {sum(not f for _, f, _ in invented)}/{len(invented)} invented numbers caught; "
        f"{sum(not f for _, f, _ in genuine)}/{len(genuine)} genuine answers passed (no false alarms) |",
        f"| Categorisation accuracy | " + ", ".join(f"{b}: {a:.1%}" for b, _, _, a in accuracy) + " |",
        "",
    ]
    if failures:
        lines += ["**Failing tests:** " + ", ".join(failures), ""]

    lines += ["## 1. Unit tests", "", "| Test file | Passed | Failed | Skipped |", "|---|---|---|---|"]
    lines += [f"| `{name}.py` | {c['passed']} | {c['failed']} | {c['skipped']} |"
              for name, c in sorted(files.items())]

    lines += ["", "## 2. Attack scorecard", "",
              "Each attack runs against the real guard, approvals, redaction, agent and audit "
              "log, with money in the sandbox so that a block is the guard's doing.", "",
              "| # | Category | Attack | Result | What happened |", "|---|---|---|---|---|"]
    lines += [f"| {i} | {cat} | {name} | {'BLOCKED' if ok else '**NOT BLOCKED**'} | {detail} |"
              for i, (cat, name, ok, detail) in enumerate(attacks, 1)]
    lines += ["", f"**Scorecard: {blocked} / {len(attacks)} blocked.**"]

    lines += ["", "## 3. Task scenarios", "",
              "Each scenario runs through the real pipeline (schema check, policy guard, owner "
              "approval with PIN, sandbox, number check, audit log). It succeeds only if the "
              "right tools ran with the right outcome, the answer passed the number check (or "
              "was correctly replaced / stopped), and the owner's steps ended correctly. "
              "Scenarios marked *fault* contain a deliberate AI mistake.", "",
              "| ID | Business | Task | Scripted AI | Keyword planner | AI calls |",
              "|---|---|---|---|---|---|"]
    planner = {s["id"]: f for s, f, _ in evaluation["planner"]}
    for s, f, calls in scripted:
        p = planner.get(s["id"])
        p_text = "-" if p is None else "pass" if not p else "fail: " + "; ".join(p)
        lines.append(f"| {s['id']} | {s['business'].split('_')[0].title()} | {s['question']}"
                     f"{' *(fault)*' if s['fault'] else ''} | {'pass' if not f else 'FAIL: ' + '; '.join(f)}"
                     f" | {p_text} | {calls} |")
    lines += ["", "**Honest notes.** The scripted mock AI follows a script, so its rate measures the "
              "pipeline, not a real AI's judgement. The keyword planner chooses tools by itself; it "
              "was improved (loan requests, \"send\") after seeing these scenarios, so its rate is "
              "optimistic. A live Gemini run is in `tests/test_live_gemini.py` (off by default)."]

    lines += ["", "## 4. Measured results", "", "### Statement cleaning and categorisation", "",
              "| Business | Transactions | Balance mismatches | Categorisation accuracy |",
              "|---|---|---|---|"]
    lines += [f"| {b} | {n:,} | {m} | {a:.1%} |" for b, n, m, a in accuracy]
    lines += ["", "The categorisation rules were written knowing the data generator, so accuracy "
              "on real statements would be lower.", "", "### Forecast backtest (last 14 days hidden)",
              "", "| Business | Sales error | Last-day error | Average daily error | Days inside range |",
              "|---|---|---|---|---|"]
    lines += [f"| {b} | {bt['sales_error_pct']:+.1%} | {kes(abs(bt['final_error']))} "
              f"{'too high' if bt['final_error'] > 0 else 'too low'} | {kes(bt['mean_abs_error'])} "
              f"| {bt['days_inside_range']}/{bt['days']} |" for b, bt in backtests]
    if h["best"]:
        lines += ["", "### Headline (Amina)", "",
                  f"- Overdraft habit: {kes(h['fees'])} in fees in {h['period_days']} days "
                  f"= about **{kes(h['habit_per_year'])} a year**.",
                  f"- Cheapest option that fits the forecast: {h['best']['name']} "
                  f"({kes(h['amount'])} over {h['days']} days) = about {kes(h['best_per_year'])} a year.",
                  f"- **Saving: about {kes(h['saving_per_year'])} a year**, if personal money is "
                  f"capped at about {kes(h['best']['cap'])} a week (now {kes(h['current'])}).",
                  "- *SACCO and bank rates are illustrative, not real quotes.*"]

    lines += ["", "## How to reproduce", "", "```", "py -m pip install -r requirements.txt",
              "py run_tests.py", "```", "",
              "Live Gemini test (uses about 4 of the free tier's 20 requests per day):", "",
              "```", '$env:RUN_LIVE_GEMINI = "1"; py -m pytest tests/test_live_gemini.py -s', "```", ""]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    return passed, failed, blocked, len(attacks), (s_pass, s_total), (p_pass, p_total)


def main():
    print("1/4 Unit tests (pytest)...")
    files, failures = run_pytest()
    print("2/4 Attack suite...")
    attacks = run_attacks()
    print("3/4 Task scenarios...")
    evaluation = run_evaluation()
    print("4/4 Measured results...")
    accuracy, backtests, h = measured_results()
    passed, failed, blocked, n_attacks, (sp, st), (pp, pt) = write_report(
        files, failures, attacks, evaluation, accuracy, backtests, h)
    print(f"\nUnit tests:      {passed} passed, {failed} failed")
    print(f"Attacks blocked: {blocked}/{n_attacks}")
    print(f"Task success:    scripted {sp}/{st}, keyword planner {pp}/{pt}")
    print(f"Saved: {OUT}")
    sys.exit(1 if failed or blocked < n_attacks or sp < st else 0)


if __name__ == "__main__":
    main()
